
public class Dtype {
	public static void main(String[] args) {
		int a=10;
		float b = 12.2f;
		double c = 12.678;
		char d = 'A';
		boolean f = true;
		System.out.println(a);
		System.out.println(b);
		System.out.println(c);
		System.out.println(d);
		System.out.println(f);
        
	}

}
